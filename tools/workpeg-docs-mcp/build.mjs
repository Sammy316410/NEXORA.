// Bundles peg/docs/workpeg/*.md into generated/docs.mjs for the hosted
// server (api/mcp.mjs). Run by Vercel's build; run it locally to test.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { readEntries } from "./server.mjs";

const out = join(dirname(fileURLToPath(import.meta.url)), "generated");
const entries = readEntries();
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "docs.mjs"), `// Generated by build.mjs. Do not edit.\nexport default ${JSON.stringify(entries)};\n`);
console.log(`bundled ${entries.length} pages`);
